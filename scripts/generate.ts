/**
 * Writes themes/mistpine, the Ghostty theme, from the mistpine spec.
 *
 *   pnpm generate          write themes/mistpine
 *   pnpm generate --check  fail if themes/mistpine is out of date
 *
 * Every value comes from palette/mistpine.json in the reference repository
 * (see lib/colors.ts). The result is linted against Ghostty's theme rules
 * and the spec's contrast floor before it is written.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { contrast, loadSpec, mix, ROOT, type Spec } from "./lib/colors.ts";

const check = process.argv.includes("--check");
const { spec, source } = await loadSpec();

/** A palette key (`bg1`) or a spec token (`terminal.cursor`, `ui.searchBg`). */
function color(key: string): string {
  const [group, name] = key.includes(".") ? key.split(".", 2) : ["palette", key];
  const table = spec[group as keyof Spec] as Record<string, unknown> | undefined;
  const value = table?.[name as string];
  const hex = typeof value === "string" ? value : (value as { hex?: string } | undefined)?.hex;
  if (!hex) throw new Error(`the spec has no color ${key}`);
  return hex.toLowerCase();
}

/** Recomputes the spec's blends, so the theme provably uses the spec's math. */
function verifyBlends(): void {
  const names: Record<string, string> = { "@terminal.background": color("terminal.background") };
  let checked = 0;
  for (const [name, token] of Object.entries(spec.ui)) {
    if (!token.derived) continue;
    const m = token.derived.match(/^mix\((\S+), \$(\w+), (\d+)%\)$/);
    if (!m) throw new Error(`ui.${name}: unknown blend ${token.derived}`);
    const [, base, key, pct] = m as unknown as [string, string, string, string];
    const got = mix(names[base] ?? color(base.replace(/^\$/, "")), color(key), Number(pct) / 100);
    if (got !== token.hex)
      throw new Error(`ui.${name}: ${token.derived} gives ${got}, spec says ${token.hex}`);
    checked++;
  }
  if (checked === 0) throw new Error("the spec has no blends: did its format change?");
}

/**
 * The theme, section by section: [Ghostty key, spec token]. Search keys need
 * Ghostty 1.3; everything else works from 1.1.
 */
const sections: { title: string[]; keys: [string, string][] }[] = [
  {
    title: ["Canvas and text: bg1 and fg3."],
    keys: [
      ["background", "terminal.background"],
      ["foreground", "terminal.foreground"],
    ],
  },
  {
    title: ["Block cursor: fg3, with the character under it in bg1."],
    keys: [
      ["cursor-color", "terminal.cursor"],
      ["cursor-text", "terminal.cursorText"],
    ],
  },
  {
    title: ["Selection: bg4 under the brightest white."],
    keys: [
      ["selection-background", "terminal.selectionBg"],
      ["selection-foreground", "terminal.selectionFg"],
    ],
  },
  {
    title: [
      "Search (Ghostty 1.3+): matches on yellow mixed 35% over bg1, as the",
      "editor's search highlight; the selected match in orange.",
    ],
    keys: [
      ["search-background", "ui.searchBg"],
      ["search-foreground", "ui.editorFg"],
      ["search-selected-background", "ui.curSearchBg"],
      ["search-selected-foreground", "ui.editorBg"],
    ],
  },
  {
    title: ["Splits: dividers are borders (bg4); unfocused splits recede toward bg0."],
    keys: [
      ["split-divider-color", "ui.border"],
      ["unfocused-split-fill", "ui.panelBg"],
    ],
  },
];

function palette(): string[] {
  if (spec.ansi.length !== 16)
    throw new Error(`the spec has ${spec.ansi.length} ANSI colors, not 16`);
  const lines = [
    "# ANSI 0-7, then the brights 8-15. 0 is bg2, not the background, so",
    "# black-on-default output stays visible; 8 is the dim gray and 15 the",
    "# brightest white. 16-255 keep Ghostty's defaults (palette-generate = true",
    "# derives them from these instead).",
  ];
  spec.ansi.forEach((token, i) => {
    if (i === 8) lines.push("");
    lines.push(`palette = ${i}=${token.hex.toLowerCase()}`);
  });
  return lines;
}

const header = [
  "# mistpine: the mistpine color scheme for Ghostty 1.3+.",
  "# https://github.com/mistpine/mistpine.ghostty · MIT License",
  "#",
  "# Save this file as ~/.config/ghostty/themes/mistpine, then add",
  "# `theme = mistpine` to your Ghostty config.",
  "#",
  "# Generated by scripts/generate.ts from the mistpine spec",
  "# (https://github.com/mistpine/mistpine/blob/main/palette/mistpine.json).",
  "# Do not edit by hand.",
];

const body = sections.flatMap(({ title, keys }) => [
  "",
  ...title.map((t) => `# ${t}`),
  ...keys.map(([key, token]) => `${key} = ${color(token)}`),
]);
const theme = `${[...header, ...body, "", ...palette()].join("\n")}\n`;

/** The color keys this theme may set (all exist in Ghostty 1.3+). */
const KNOWN_KEYS = new Set([
  "background",
  "foreground",
  "cursor-color",
  "cursor-text",
  "selection-background",
  "selection-foreground",
  "search-background",
  "search-foreground",
  "search-selected-background",
  "search-selected-foreground",
  "split-divider-color",
  "unfocused-split-fill",
  "palette",
]);

/** Checks the file the way Ghostty reads it, plus the spec's contrast floor. */
function lint(text: string): Map<string, string> {
  const values = new Map<string, string>();
  const seen = new Set<number>();
  text.split("\n").forEach((line, n) => {
    const at = `themes/mistpine:${n + 1}`;
    if (line !== line.trimEnd()) throw new Error(`${at}: trailing whitespace`);
    if (line === "" || line.startsWith("#")) return;
    const m = line.match(/^([a-z-]+) = (\S+)$/);
    if (!m) throw new Error(`${at}: not a "key = value" line: ${line}`);
    const [, key, value] = m as unknown as [string, string, string];
    if (!KNOWN_KEYS.has(key)) throw new Error(`${at}: ${key} is not a Ghostty color key`);
    if (key === "palette") {
      const p = value.match(/^(\d+)=(#[0-9a-f]{6})$/);
      if (!p) throw new Error(`${at}: palette must be N=#rrggbb`);
      const i = Number(p[1]);
      if (i > 15 || seen.has(i)) throw new Error(`${at}: palette ${i} is out of range or repeated`);
      seen.add(i);
      values.set(`palette ${i}`, p[2] as string);
      return;
    }
    if (!/^#[0-9a-f]{6}$/.test(value)) throw new Error(`${at}: ${key} must be #rrggbb`);
    if (values.has(key)) throw new Error(`${at}: ${key} is set twice`);
    values.set(key, value);
  });
  if (seen.size !== 16) throw new Error(`themes/mistpine sets ${seen.size} palette colors, not 16`);

  // Text over its own background must clear WCAG AA (4.5:1), as the spec asks.
  const pairs: [string, string][] = [
    ["foreground", "background"],
    ["cursor-text", "cursor-color"],
    ["selection-foreground", "selection-background"],
    ["search-foreground", "search-background"],
    ["search-selected-foreground", "search-selected-background"],
  ];
  for (const [fg, bg] of pairs) {
    const ratio = contrast(values.get(fg) as string, values.get(bg) as string);
    if (ratio < 4.5) throw new Error(`${fg} on ${bg} is ${ratio.toFixed(2)}:1, below 4.5:1`);
  }
  return values;
}

verifyBlends();
lint(theme);

const out = join(ROOT, "themes", "mistpine");
if (check) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {}
  if (current !== theme) {
    console.error("themes/mistpine is out of date: run pnpm generate");
    process.exit(1);
  }
  console.log(`themes/mistpine is up to date (spec: ${source})`);
} else {
  writeFileSync(out, theme);
  console.log(`wrote themes/mistpine (spec: ${source})`);
}
